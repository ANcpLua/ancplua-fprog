using System.Threading.Tasks;
using ancplua_fprog.Tests.Shared;
using Microsoft.CodeAnalysis.Testing;
using Microsoft.VisualStudio.TestTools.UnitTesting;

namespace ancplua_fprog.Tests.Rules;

[TestClass]
public sealed class Fp0403Tests(TestContext testContext)
{
    [TestMethod]
    public Task FP0403_OpenClassCaseOutsideCore_Reports()
    {
        return VerifyAsync("""
                           public closed class Shape;
                           public class {|FP0403:Circle|} : Shape;
                           """);
    }

    [TestMethod]
    public Task FP0403_OpenAbstractRecordCaseInCore_Reports()
    {
        return VerifyAsync("""
                           [assembly: Fprog.FunctionalCore]

                           public closed record Shape
                           {
                               public abstract record {|FP0403:Circle|}(double Radius) : Shape;
                           }
                           """);
    }

    [TestMethod]
    public Task FP0403_OpenLeafOfNestedClosedCase_Reports()
    {
        return VerifyAsync("""
                           public closed record Shape;
                           public closed record Polygon : Shape;
                           public record {|FP0403:Square|}(int Length) : Polygon;
                           """);
    }

    [TestMethod]
    public Task FP0403_PartialCaseReportsOnceAtFirstName_Reports()
    {
        return VerifyAsync("""
                           public closed class Result<T>;
                           public partial class {|FP0403:Ok|};
                           public partial class Ok : Result<int>;
                           """);
    }

    [TestMethod]
    public Task FP0403_SealedAndClosedDirectCases_NoReport()
    {
        return VerifyAsync("""
                           public closed record Shape
                           {
                               public sealed record Circle(double Radius) : Shape;
                           }

                           public closed record Polygon : Shape;
                           public sealed record Square(double Side) : Polygon;

                           public closed class Result<T>;
                           public sealed class Number : Result<int>;
                           """);
    }

    [TestMethod]
    public Task FP0403_ClassCasesOfNativeUnionAndOrdinaryBaseAreAllowed_NoReport()
    {
        return VerifyAsync("""
                           public abstract record Shape;
                           public record Circle(double Radius) : Shape;
                           public record Square(double Side) : Shape;
                           public union Round(Circle, Square);
                           """);
    }

    [TestMethod]
    public Task FP0403_OnlyTheDirectOpenCase_Reports()
    {
        return VerifyAsync("""
                           public closed class Shape
                           {
                               public class {|FP0403:Polygon|} : Shape;
                           }

                           public class Square : Shape.Polygon;
                           """);
    }

    [TestMethod]
    public Task FP0403_SubtypeOfReferencedOpenCase_NoReport()
    {
        const string library = """
                               namespace Domain;

                               public closed class Shape;
                               public class OpenCase : Shape;
                               """;
        return FpAnalyzerTestHost.VerifyRuleWithReferencedAssemblyAsync("FP0403", """
            public class ExternalSubtype : Domain.OpenCase;
            """, library, testContext.CancellationToken);
    }

    [TestMethod]
    public Task CompilerRejectsDerivationFromReferencedClosedCase()
    {
        return FpAnalyzerTestHost.VerifyRuleWithReferencedAssemblyAsync("FP0403", """
            public sealed record {|#0:ExternalSubtype|} : Domain.Polygon;
            """, ReferencedAssemblySources.Unions, testContext.CancellationToken,
            DiagnosticResult.CompilerError("CS9382").WithLocation(0).WithArguments("ExternalSubtype", "Domain.Polygon"));
    }

    [TestMethod]
    public Task FP0403_GeneratedCode_NoReport()
    {
        return VerifyAsync("""
                           // <auto-generated/>
                           public closed class Shape;
                           public class Circle : Shape;
                           """);
    }

    private Task VerifyAsync(string source)
    {
        return FpAnalyzerTestHost.VerifyRuleAsync("FP0403", source, testContext.CancellationToken);
    }
}
