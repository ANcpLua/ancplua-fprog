using System.Threading.Tasks;
using Microsoft.VisualStudio.TestTools.UnitTesting;

namespace ancplua_fprog.Tests.Rules;

[TestClass]
public sealed class Fp0401Tests(TestContext testContext)
{
    [TestMethod]
    public Task FP0401_ConcreteAndAbstractClassesInCore_Reports()
    {
        return VerifyAsync("""
                           [Fprog.FunctionalCore]
                           public class {|FP0401:Open|};

                           [Fprog.FunctionalCore]
                           public abstract class {|FP0401:Base|};
                           """);
    }

    [TestMethod]
    public Task FP0401_OpenRecordsInCore_Reports()
    {
        return VerifyAsync("""
                           [Fprog.FunctionalCore]
                           public record {|FP0401:Position|}(int X, int Y);

                           [Fprog.FunctionalCore]
                           public abstract record class {|FP0401:Tagged|}(int Tag);
                           """);
    }

    [TestMethod]
    public Task FP0401_OpenTypeNestedInsideCore_Reports()
    {
        return VerifyAsync("""
                           [Fprog.FunctionalCore]
                           public static class Outer<T>
                           {
                               public sealed class Middle
                               {
                                   public class {|FP0401:Inner|};
                               }
                           }
                           """);
    }

    [TestMethod]
    public Task FP0401_PartialCoreTypeReportsAtFirstName_Reports()
    {
        return VerifyAsync("""
                           [assembly: Fprog.FunctionalCore]

                           public partial class {|FP0401:Partial|};
                           public partial class Partial;
                           """);
    }

    [TestMethod]
    public Task FP0401_ClosedSealedStaticAndNonClassTypes_NoReport()
    {
        return VerifyAsync("""
                           [assembly: Fprog.FunctionalCore]

                           public closed class Shape;
                           public sealed class Circle : Shape;
                           public closed record Fruit;
                           public sealed record Apple : Fruit;
                           public static class Helpers;
                           public struct Point;
                           public readonly record struct Vector(int X, int Y);
                           public interface IGeometry;
                           public enum Bearing { North, South }
                           public delegate int Area(int radius);
                           public union Round(Circle, Apple);
                           """);
    }

    [TestMethod]
    public Task FP0401_OpenClassAndRecordOutsideCore_NoReport()
    {
        return VerifyAsync("""
                           public abstract record ApiResponse;
                           public class ResponseHandler;
                           """);
    }

    [TestMethod]
    public Task FP0401_OpenCaseInCoreBelongsToFP0403_NoReport()
    {
        return VerifyAsync("""
                           [assembly: Fprog.FunctionalCore]

                           public closed class Shape;
                           public class Circle : Shape;
                           """);
    }

    [TestMethod]
    public Task FP0401_GeneratedCode_NoReport()
    {
        return VerifyAsync("""
                           // <auto-generated/>
                           [Fprog.FunctionalCore]
                           public class Generated;
                           """);
    }

    private Task VerifyAsync(string source)
    {
        return FpAnalyzerTestHost.VerifyRuleAsync("FP0401", source, testContext.CancellationToken);
    }
}
