using System.Threading.Tasks;
using ancplua_fprog.Tests.Shared;
using Microsoft.VisualStudio.TestTools.UnitTesting;

namespace ancplua_fprog.Tests.Rules;

[TestClass]
public sealed class Fp0803Tests(TestContext testContext)
{
    [TestMethod]
    public Task FP0803_ShellDerivesFromCoreClassWithPrimaryConstructor_Reports()
    {
        return VerifyAsync("""
                           namespace Domain
                           {
                               [Fprog.FunctionalCore]
                               public abstract class Rule(int order) { public int Order { get; } = order; }
                           }

                           public sealed class RuleAdapter() : Domain.{|FP0803:Rule|}(7);
                           """);
    }

    [TestMethod]
    public Task FP0803_ShellClassStructAndInterfaceExtendCoreInterfaces_Reports()
    {
        return VerifyAsync("""
                           using Counter = Contracts.ICount<int>;

                           namespace Contracts
                           {
                               [Fprog.FunctionalCore]
                               public interface ICount<T> { T Get(); }
                           }

                           public sealed class ClassCounter : Contracts.{|FP0803:ICount|}<int>
                           {
                               public int Get() => 1;
                           }

                           public readonly struct ValueCounter : {|FP0803:Counter|}
                           {
                               public int Get() => 1;
                           }

                           public interface ICounter : {|FP0803:Counter|};
                           """);
    }

    [TestMethod]
    public Task FP0803_CoreDescendantAndNonCoreInheritance_NoReport()
    {
        return VerifyAsync("""
                           [Fprog.FunctionalCore]
                           public static class Domain
                           {
                               public closed record State;
                               public sealed record Ready : State;
                           }

                           public interface IContract;
                           public sealed class Adapter : IContract;
                           """);
    }

    [TestMethod]
    public Task FP0803_ShellImplementsReferencedCoreInterface_Reports()
    {
        return FpAnalyzerTestHost.VerifyRuleWithReferencedAssemblyAsync("FP0803", """
            public sealed class ShellCounter : Domain.{|FP0803:ICounter|}
            {
                public int Get() => 1;
            }
            """, ReferencedAssemblySources.CoreTypes, testContext.CancellationToken);
    }

    [TestMethod]
    public Task FP0803_CoreImplementsReferencedCoreInterface_NoReport()
    {
        return FpAnalyzerTestHost.VerifyRuleWithReferencedAssemblyAsync("FP0803", """
            [Fprog.FunctionalCore]
            public sealed class CoreCounter : Domain.ICounter
            {
                public int Get() => 1;
            }
            """, ReferencedAssemblySources.CoreTypes, testContext.CancellationToken);
    }

    [TestMethod]
    public Task FP0803_AssemblyCore_NoReport()
    {
        return VerifyAsync("""
                           [assembly: Fprog.FunctionalCore]

                           public interface ICounter;
                           public sealed class Counter : ICounter;
                           """);
    }

    [TestMethod]
    public Task FP0803_GeneratedCode_NoReport()
    {
        return VerifyAsync("""
                           // <auto-generated/>
                           [Fprog.FunctionalCore]
                           public interface IDomain;
                           public class Shell : IDomain;
                           """);
    }

    private Task VerifyAsync(string source)
    {
        return FpAnalyzerTestHost.VerifyRuleAsync("FP0803", source, testContext.CancellationToken);
    }
}
